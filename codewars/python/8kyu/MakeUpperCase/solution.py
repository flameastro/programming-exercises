# Write a function which converts the input string to uppercase.
def make_upper_case(s):
    return s.upper()


if __name__ == "__main__":
    print(make_upper_case("abcdef"))  # ABCDEF
    print(make_upper_case("testing the code"))  # TESTING THE CODE
    print(make_upper_case("is this gonna be UPPERCASE?"))  # IS THIS GONNA BE UPPERCASE?
