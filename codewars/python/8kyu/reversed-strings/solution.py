# Complete the solution so that it reverses the string passed into it.
# 'world'  =>  'dlrow'
# 'word'   =>  'drow'
def solution(string):
    return string[::-1]


if __name__ == "__main__":
    print(solution("world"))  # dlrow
    print(solution("codewars"))  # srawedoc
    print(solution("reversed string"))  # gnirts desrever
